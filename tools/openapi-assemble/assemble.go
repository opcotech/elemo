package main

import (
	"path/filepath"

	"gopkg.in/yaml.v3"
)

const bundleHeader = `# Code generated by tools/openapi-assemble; DO NOT EDIT.
# Edit files in api/openapi/src/ instead, then run: make generate.openapi
`

const rootFile = "openapi.yaml"

func assemble(srcDir string, layout Layout) (*yaml.Node, error) {
	root, err := loadMappingFile(filepath.Join(srcDir, rootFile))
	if err != nil {
		return nil, err
	}

	paths, err := mergeFiles(srcDir, layout.PathFiles)
	if err != nil {
		return nil, err
	}

	schemas, err := mergeFiles(srcDir, layout.SchemaFiles)
	if err != nil {
		return nil, err
	}

	requestBodies, err := mergeFiles(srcDir, layout.RequestBodyFiles)
	if err != nil {
		return nil, err
	}

	parameters, err := loadMappingFile(filepath.Join(srcDir, layout.ParametersFile))
	if err != nil {
		return nil, err
	}

	responses, err := loadMappingFile(filepath.Join(srcDir, layout.ResponsesFile))
	if err != nil {
		return nil, err
	}

	securitySchemes, err := loadMappingFile(filepath.Join(srcDir, layout.SecuritySchemesFile))
	if err != nil {
		return nil, err
	}

	components := &yaml.Node{Kind: yaml.MappingNode}
	setMappingKey(components, "schemas", schemas)
	setMappingKey(components, "examples", &yaml.Node{Kind: yaml.MappingNode})
	setMappingKey(components, "securitySchemes", securitySchemes)
	setMappingKey(components, "responses", responses)
	setMappingKey(components, "parameters", parameters)
	setMappingKey(components, "requestBodies", requestBodies)

	deleteMappingKey(root, "paths")
	deleteMappingKey(root, "components")
	setMappingKey(root, "components", components)
	setMappingKey(root, "paths", paths)

	return root, nil
}

func writeBundle(path string, node *yaml.Node) error {
	return writeYAMLFile(path, node, bundleHeader)
}
